const globalReverseMap = {};
const reverseCharMaps = {};

for (const [styleName, map] of Object.entries(charMaps)) {
  reverseCharMaps[styleName] = {};
  for (const [ascii, styled] of Object.entries(map)) {
    globalReverseMap[styled] = ascii;
    reverseCharMaps[styleName][styled] = ascii;
  }
}

export const applyStyle = (text, style) => {
  if (style === 'underline') {
    if (text.includes('\u0332')) {
      return text.replace(/\u0332/g, '');
    }
    return Array.from(text).map(char => {
      if (char.trim() === '') return char;
      return char + '\u0332';
    }).join('');
  }
  
  if (style === 'strikethrough') {
    if (text.includes('\u0336')) {
      return text.replace(/\u0336/g, '');
    }
    return Array.from(text).map(char => {
      if (char.trim() === '') return char;
      return char + '\u0336';
    }).join('');
  }
  
  const map = charMaps[style];
  if (!map) return text;

  const normalizedText = Array.from(text).map(char => globalReverseMap[char] || char).join('');
  
  const originalChars = Array.from(text);
  const hasMappableChars = originalChars.some(char => globalReverseMap[char] || map[char]);
  
  const allMappableAreThisStyle = originalChars.every(char => {
    if (globalReverseMap[char]) {
      return reverseCharMaps[style][char];
    }
    if (map[char]) {
      return false;
    }
    return true;
  });

  const hasAnyOfThisStyle = originalChars.some(char => reverseCharMaps[style][char]);

  if (hasMappableChars && allMappableAreThisStyle && hasAnyOfThisStyle) {
    return normalizedText;
  }

  return Array.from(normalizedText).map(char => map[char] || char).join('');
};

export const convertLineBreaks = (text) => {
  // Replace newlines with the Zero-Width Space or Thin Space
  // Unicode Thin Space: U+2009 (\u2009)
  // To keep line breaks visible but bypass Instagram's removal of empty lines, 
  // we add a Zero Width Space or Thin Space to empty lines.
  
  return text.split('\n').map(line => {
    if (line.trim() === '') {
      return '\u2009'; // Thin space
    }
    return line;
  }).join('\n');
};
